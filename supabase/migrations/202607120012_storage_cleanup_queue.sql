-- Durable cleanup for private Storage objects whose authoritative DB row was
-- deleted. Client-side best-effort removal remains fast, while this queue
-- guarantees a server retry path after network/process failures.

create table if not exists public.storage_cleanup_jobs (
  id bigint generated by default as identity primary key,
  bucket_id text not null check (
    bucket_id in (
      'chat-images',
      'memory-album-photos',
      'travel-city-photos',
      'world-country-photos'
    )
  ),
  object_path text not null check (length(trim(object_path)) > 0),
  status text not null default 'pending'
    check (status in ('pending', 'processing', 'failed')),
  attempts integer not null default 0 check (attempts >= 0),
  available_at timestamptz not null default now(),
  locked_at timestamptz,
  worker_id text,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (bucket_id, object_path)
);

create index if not exists storage_cleanup_jobs_claim_idx
  on public.storage_cleanup_jobs(status, available_at, id);

alter table public.storage_cleanup_jobs enable row level security;
revoke all on table public.storage_cleanup_jobs from public, anon, authenticated;

create or replace function public.enqueue_storage_cleanup(
  target_bucket text,
  target_path text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if target_path is null or trim(target_path) = '' then
    return;
  end if;
  if target_bucket not in (
    'chat-images',
    'memory-album-photos',
    'travel-city-photos',
    'world-country-photos'
  ) then
    raise exception 'STORAGE_CLEANUP_BUCKET_NOT_ALLOWED';
  end if;

  insert into public.storage_cleanup_jobs(bucket_id, object_path)
  values (target_bucket, target_path)
  on conflict (bucket_id, object_path) do update
  set status = 'pending',
      available_at = now(),
      locked_at = null,
      worker_id = null,
      last_error = null,
      updated_at = now();
end;
$$;

revoke all on function public.enqueue_storage_cleanup(text, text)
  from public, anon, authenticated;

create or replace function public.queue_deleted_storage_object()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  bucket_name text := tg_argv[0];
  path_column text := tg_argv[1];
  deleted_path text;
begin
  deleted_path := to_jsonb(old) ->> path_column;
  perform public.enqueue_storage_cleanup(bucket_name, deleted_path);
  return old;
end;
$$;

