create or replace function public.claim_storage_cleanup_jobs(
  worker_id text,
  batch_size integer default 50
)
returns table (
  id bigint,
  bucket_id text,
  object_path text
)
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  with candidates as (
    select job.id
    from public.storage_cleanup_jobs job
    where (
      job.status = 'pending'
      and job.available_at <= now()
    ) or (
      job.status = 'processing'
      and job.locked_at < now() - interval '10 minutes'
    )
    order by job.available_at, job.id
    for update skip locked
    limit greatest(1, least(coalesce(batch_size, 50), 100))
  ), claimed as (
    update public.storage_cleanup_jobs job
    set status = 'processing',
        locked_at = now(),
        worker_id = claim_storage_cleanup_jobs.worker_id,
        attempts = job.attempts + 1,
        updated_at = now()
    from candidates
    where job.id = candidates.id
    returning job.id, job.bucket_id, job.object_path
  )
  select claimed.id, claimed.bucket_id, claimed.object_path
  from claimed;
end;
$$;

create or replace function public.finish_storage_cleanup_job(
  target_job_id bigint,
  succeeded boolean,
  error_message text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  attempt_count integer;
begin
  if succeeded then
    delete from public.storage_cleanup_jobs where id = target_job_id;
    return;
  end if;

  select attempts into attempt_count
  from public.storage_cleanup_jobs
  where id = target_job_id;

  update public.storage_cleanup_jobs
  set status = case when coalesce(attempt_count, 0) >= 8
      then 'failed' else 'pending' end,
      available_at = now() +
        make_interval(secs => least(3600, (30 * power(2, greatest(0,
          coalesce(attempt_count, 1) - 1)))::integer)),
      locked_at = null,
      worker_id = null,
      last_error = left(coalesce(error_message, 'STORAGE_REMOVE_FAILED'), 1000),
      updated_at = now()
  where id = target_job_id;
end;
$$;

revoke all on function public.claim_storage_cleanup_jobs(text, integer)
  from public, anon, authenticated;
revoke all on function public.finish_storage_cleanup_job(bigint, boolean, text)
  from public, anon, authenticated;
grant execute on function public.claim_storage_cleanup_jobs(text, integer)
  to service_role;
grant execute on function public.finish_storage_cleanup_job(bigint, boolean, text)
  to service_role;

create or replace function public.invoke_storage_cleanup_worker()
returns void
language plpgsql
security definer
set search_path = public, vault, net
as $$
declare
  project_url text;
  service_role_key text;
begin
  select decrypted_secret into project_url
  from vault.decrypted_secrets
  where name = 'project_url'
  limit 1;

  select decrypted_secret into service_role_key
  from vault.decrypted_secrets
  where name = 'service_role_key'
  limit 1;

  if project_url is null or service_role_key is null then
    raise warning 'storage cleanup worker skipped: vault secrets missing';
    return;
  end if;

  perform net.http_post(
    url := rtrim(project_url, '/') || '/functions/v1/process-storage-cleanup',
    headers := jsonb_build_object(
      'content-type', 'application/json',
      'authorization', 'Bearer ' || service_role_key
    ),
    body := '{}'::jsonb,
    timeout_milliseconds := 50000
  );
end;
$$;

revoke all on function public.invoke_storage_cleanup_worker()
  from public, anon, authenticated;
grant execute on function public.invoke_storage_cleanup_worker()
  to service_role;

do $$
declare
  existing_job_id bigint;
begin
  select jobid into existing_job_id
  from cron.job
  where jobname = 'dear-storage-cleanup'
  limit 1;
  if existing_job_id is not null then
    perform cron.unschedule(existing_job_id);
  end if;
  perform cron.schedule(
    'dear-storage-cleanup',
    '*/5 * * * *',
    $command$select public.invoke_storage_cleanup_worker();$command$
  );
end $$;
